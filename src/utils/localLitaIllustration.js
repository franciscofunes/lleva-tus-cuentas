// Decorative-only browser image generation. The model never sees account data,
// transaction metadata, currency values, or context from the LITA iframe.
// This opt-in uses the binary runonweb Bonsai Image 4B model via WebGPU.
const DECORATIVE_PROMPT = 'Minimal premium editorial abstract finance-inspired artwork. Flowing translucent violet and blue ribbons, smooth geometric shapes, soft lighting, rich midnight navy background, elegant composition, no letters, no numbers, no logos, no money symbols, no text.';
let generating = false;

/**
 * Cheap, download-free browser preflight. navigator.deviceMemory is approximate
 * and often capped by Chrome; it cannot guarantee that the GPU has free VRAM.
 * This guard avoids kicking off a 3.4 GB model download on small devices.
 */
export async function checkLitaLocalIllustrationCapability() {
  if (typeof navigator === 'undefined' || !navigator.gpu ||
    typeof navigator.gpu.requestAdapter !== 'function') {
    return {
      supported: false,
      reason: 'Este navegador no ofrece WebGPU. Bonsai Image 4B necesita Chrome o Edge con WebGPU y una GPU compatible; no tiene modo alternativo en CPU.',
    };
  }
  if (typeof navigator.deviceMemory === 'number' && navigator.deviceMemory < 8) {
    return {
      supported: false,
      reason: 'Este navegador informa menos de 8 GB de memoria. Bloqueamos la descarga del modelo de 3,4 GB para evitar que el teléfono se quede sin memoria. Probalo desde una computadora con GPU compatible.',
    };
  }
  try {
    const adapter = await navigator.gpu.requestAdapter();
    if (!adapter) {
      return {
        supported: false,
        reason: 'WebGPU está presente, pero el navegador no encontró una GPU compatible. Revisá chrome://gpu o probá Chrome/Edge actualizado en una computadora.',
      };
    }
    return { supported: true, reason: '' };
  } catch {
    return {
      supported: false,
      reason: 'El navegador rechazó el acceso a la GPU. Probá Chrome/Edge actualizado y revisá la disponibilidad de WebGPU.',
    };
  }
}

// Safe, user-actionable messages. Never expose raw model URLs, prompts or
// technical internal errors from SDKs through the iframe.
export function describeLitaLocalIllustrationError(error) {
  const message = String(error?.message || error?.litaOriginalMessage || error || '').slice(0, 500);
  const stage = typeof error?.litaStage === 'string' ? error.litaStage : 'unknown';
  const stageLabel = {
    runtime: 'la preparación del motor WebGPU',
    weights: 'la carga de los archivos del modelo',
    generating: 'la generación de la ilustración',
    validation: 'la validación del PNG',
  }[stage] || 'la ejecución local';

  if (/quota|no space|disk full|QuotaExceededError|indexeddb.*(?:fail|error)/i.test(message)) {
    return 'Error durante ' + stageLabel +
      ': el navegador no pudo almacenar los archivos del modelo (~3,4 GB). Revisá el espacio disponible y probá de nuevo.';
  }
  if (/out.of.memory|oom|allocation|buffer|device lost|gpu device|gpu.*memory/i.test(message)) {
    return 'Error durante ' + stageLabel +
      ': la GPU o la memoria disponible no alcanzó para ejecutar Bonsai Image 4B.';
  }
  if (/fetch|network|download|connection|http 4|http 5|failed to load/i.test(message)) {
    return 'Error durante ' + stageLabel +
      ': falló la descarga de los archivos del modelo. Revisá Wi-Fi, espacio libre y acceso a Hugging Face.';
  }
  if (/webgpu|adapter|gpu.*unavailable|not supported/i.test(message)) {
    return 'Error durante ' + stageLabel +
      ': la GPU no admite alguna operación que necesita Bonsai Image 4B, aunque WebGPU esté disponible.';
  }
  if (stage === 'runtime') {
    return 'Falló la preparación del motor local de imágenes antes de descargar el modelo. Puede ser una incompatibilidad del navegador o un archivo del runtime que no cargó.';
  }
  if (stage === 'weights') {
    return 'Falló la carga del modelo Bonsai Image 4B (~3,4 GB). WebGPU está disponible, pero eso no garantiza memoria gráfica, espacio ni compatibilidad del modelo.';
  }
  if (stage === 'generating') {
    return 'El modelo se cargó, pero falló la generación de la imagen en la GPU. Puede faltar memoria gráfica.';
  }
  return 'Falló la generación local de Bonsai Image 4B durante ' + stageLabel +
    '. El reporte PNG sigue disponible.';
}

export async function generateLitaLocalIllustration(onProgress = () => {}) {
  if (generating) throw new Error('Ya hay una ilustración local en proceso.');
  const capability = await checkLitaLocalIllustrationCapability();
  if (!capability.supported) throw new Error(capability.reason);

  generating = true;
  let generator = null;
  let stage = 'runtime';
  try {
    onProgress(0, 'runtime');
    // Generated by scripts/build-browser-ocr.cjs at build time, never eagerly loaded.
    const { ImageGenerator, isImageGenerationSupported } = await import('../generated/browser-ai/image');
    if (!(await isImageGenerationSupported())) {
      throw new Error('La GPU disponible no permite ejecutar la generación de imágenes.');
    }
    generator = new ImageGenerator({
      size: 'binary', width: 512, height: 512, steps: 4,
      onProgress: ({ progress, status }) => {
        const phase = status === 'generating' || status === 'done' ? 'generating' : 'weights';
        stage = phase;
        if (Number.isFinite(progress)) {
          onProgress(Math.min(100, Math.max(0, Math.round(progress))), phase);
        }
      },
    });
    // The SDK also lazy-loads inside generate(), but explicitly loading first
    // makes the documented load -> generate -> dispose sequence observable.
    stage = 'weights';
    onProgress(0, 'weights');
    await generator.load();
    stage = 'generating';
    onProgress(0, 'generating');
    const result = await generator.generate(DECORATIVE_PROMPT);
    stage = 'validation';
    // Canvas/worker Blobs may cross JS realms, so do not rely on instanceof Blob.
    // Validate the generated local image as a small PNG Blob-like value.
    if (!result?.image || result.image.type !== 'image/png' ||
      typeof result.image.size !== 'number' || result.image.size <= 0 ||
      result.image.size > 8_000_000 || typeof result.image.slice !== 'function') {
      throw new Error('No se pudo producir una ilustración PNG válida.');
    }
    return result.image;
  } catch (error) {
    // Preserve the failure phase locally but never forward raw model URLs or
    // internal SDK exception text across the trusted iframe bridge.
    const wrapped = new Error(String(error?.message || error || 'Local model failed').slice(0, 500));
    wrapped.litaStage = stage;
    throw wrapped;
  } finally {
    try { generator?.dispose(); } catch { /* Cleanup must not mask model errors. */ }
    generating = false;
  }
}
